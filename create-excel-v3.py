def sty_h(ws, row, mc):
    for c in range(1, mc+1):
        cl = ws.cell(row=row, column=c)
        cl.font = H_FONT; cl.fill = H_FILL
        cl.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        cl.border = TB

def sty_sec(ws, row, mc, label):
    ws.merge_cells(start_row=row, start_column=1, end_row=row, end_column=mc)
    cl = ws.cell(row=row, column=1, value=label)
    cl.font = S_FONT; cl.fill = S_FILL; cl.alignment = Alignment(horizontal="left")
    for c in range(1, mc+1):
        ws.cell(row=row, column=c).fill = S_FILL
        ws.cell(row=row, column=c).border = TB

def sty_r(ws, r, mc):
    for c in range(1, mc+1):
        cl = ws.cell(row=r, column=c)
        cl.font = NF; cl.border = TB
        cl.alignment = Alignment(vertical="center", wrap_text=True)
        cl.fill = EX_FILL

